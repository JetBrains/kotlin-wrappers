external interface ToString {

    /**
     * [MDN Reference](https://developer.mozilla.org/docs/Web/JavaScript/Reference/Global_Objects/Symbol/toStringTag)
     */
    @JsSymbol("toStringTag")
    fun `[@@toStringTag]`(): String
}
